# -*- coding: utf-8 -*-
"""外汇资金台账（苏姆本位）· 表头/子表名/公式体检与修正

这份台账把本位币从人民币改成了苏姆（UZS），但整套表是按人民币本位做的，
改了【参数设置】的本位币之后，下面这些地方没跟着走：

★ 真 bug 三处
  ① 【月度汇率】右边「月末汇率」区的币种表头是 CNY / USD / HKD …，
     跟左边「记账汇率」区（UZS / CNY / USD / EUR …）错开了一位，而且多出个 HKD。
     公式是 INDEX(月末汇率区, 0, MATCH(币种, 汇率币种头, 0)) —— 按**位置**取的，
     所以你在标着「USD」的那一列填月末汇率，系统实际当成 CNY 用。
     改成 =B$5 … =I$5，永远跟左边同一套币种，不可能再错位。
  ② 【核对表】第 6 项「银行子表张数 = 账户档案里的账户数」写死了 =6-COUNTA(账户名)，
     那个 6 是做模板时的子表数。现在只有 5 个账户 5 张子表，它却报「差 1 张」。
     改成用 INDIRECT 真去数「有几个账户确实有子表」。
  ③ 【核对表】第 2 项「期末原币合计 = 期初 + 流水净额」差 0.01：
     【账户余额表】把期初 ROUND 到两位再用，而核对公式拿的是没 ROUND 的原值。
     这份账的期初余额带一堆小数（-910124979.333333 这种），差额就出来了。
     核对公式两边改成同一个口径。

★ 表头文字：所有「人民币」字样的列标题改成跟着本位币走的公式（现在显示「苏姆」），
  本位币以后再改，表头自己跟着变。摘要列里客户自己写的「人民币」原样不动。

★ 使用说明：补一节「人民币换美元怎么录」，并把过时的示例说明改掉。

跑法：python3 fix_uzs.py <入.xlsx> <出.xlsx>
"""
import sys
import openpyxl
from copy import copy

SRC, OUT = sys.argv[1], sys.argv[2]
wb = openpyxl.load_workbook(SRC)

CUR = '本位币名'          # 定义名称，指向参数设置!$B$8


def hdr(txt_parts):
    """拼一个跟着本位币走的表头公式，例如 ["折", CUR] → ="折"&本位币名"""
    out = []
    for p in txt_parts:
        out.append(p if p == CUR else '"' + p + '"')
    return '=' + '&'.join(out)


# ══════════════════════════════════════════════════════════
# ① 参数设置：加一个「本位币名称」自动格，后面所有表头都引它
# ══════════════════════════════════════════════════════════
ws = wb['参数设置']
ws['A8'] = '本位币名称'
ws['A8']._style = copy(ws['A7']._style)
ws['B8'] = '=IFERROR(INDEX($M$11:$M$18,MATCH($B$4,$L$11:$L$18,0)),$B$4)'
ws['B8']._style = copy(ws['B7']._style)
ws['C8'] = '自动 = 币种清单里本位币对应的中文名。所有报表的「折××」表头都跟着它走。'
ws['C8']._style = copy(ws['C7']._style)
ws['I10'] = hdr(['期初', CUR, '成本'])

from openpyxl.workbook.defined_name import DefinedName
if CUR in wb.defined_names:
    del wb.defined_names[CUR]
wb.defined_names.add(DefinedName(CUR, attr_text='参数设置!$B$8'))

# ══════════════════════════════════════════════════════════
# ② 月度汇率：月末汇率区的币种表头跟左边对齐  ★真 bug
# ══════════════════════════════════════════════════════════
ws = wb['月度汇率']
for dst, src in zip('KLMNOPQR', 'BCDEFGHI'):
    ws[f'{dst}5'] = f'={src}$5'
ws['A2'] = ('左边【记账汇率】是流水折本位币用的；右边【月末汇率】是月末重估用的，空着就自动用左边那个。'
            '★ 两边的币种是同一套、同一个顺序（右边表头直接引左边），别手工改右边的币种名。'
            '某月没填？自动往前找最近一个填过的月份，并在核对表点名。'
            '汇率的意思统一是「1 个原币 = 多少本位币」，比如 CNY 填 1700 就是 1 元 = 1700 苏姆。')

# ══════════════════════════════════════════════════════════
# ③ 流水录入 / 账户子表 的表头
# ══════════════════════════════════════════════════════════
wb['流水录入']['L5'] = hdr(['折', CUR])
wb['流水录入']['N5'] = hdr(['账面', CUR, '余额'])

SUBS = [ws.title for ws in wb.worksheets
        if ws['A2'].value == '账户名称' and ws.title not in ('流水录入',)]
for n in SUBS:
    s = wb[n]
    s['K3'] = hdr(['期末', CUR])
    s['L5'] = hdr(['折', CUR])
    s['N5'] = hdr(['账面', CUR, '余额'])
print(f'  ✓ 账户子表 {len(SUBS)} 张表头已跟本位币：{SUBS}')

# ══════════════════════════════════════════════════════════
# ④ 账户余额表
# ══════════════════════════════════════════════════════════
ws = wb['账户余额表']
ws['A1'] = hdr(['账户余额表 · 每个账户一行，原币和', CUR, '各算各的'])
ws['A2'] = hdr(['「账面', CUR, '成本」= 期初成本 + 每笔按当时汇率折的', CUR,
                 '；「期末', CUR, '(重估)」= 期末原币 × 期末汇率。两者之差就是汇兑损益 —— ',
                 '这是外汇台账跟普通资金台账唯一的区别，别把两个口径混着加。'])
ws['J5'] = hdr(['期末', CUR, '(重估)'])
ws['K5'] = hdr(['账面', CUR, '成本'])
ws['E39'] = hdr(['折', CUR])
ws['F39'] = hdr(['账面', CUR, '成本'])
ws['M36'] = hdr(['「期末', CUR, '合计」就是公司的资金总额（', CUR, '口径）'])
n = 0
for r in range(6, 36):
    v = ws[f'M{r}'].value
    if isinstance(v, str) and '人民币这几列算不出来' in v:
        ws[f'M{r}'] = v.replace('" 还没填汇率，人民币这几列算不出来"',
                                '" 还没填汇率，"&' + CUR + '&"那几列算不出来"')
        n += 1
print(f'  ✓ 账户余额表：表头与 {n} 行核对提示改成跟着本位币')

# ══════════════════════════════════════════════════════════
# ⑤ 月度汇报表 / 收支分类报表 / 资金日报表 / 区间查询
# ══════════════════════════════════════════════════════════
ws = wb['月度汇报表']
ws['A1'] = hdr(['月度汇报表 · 全部折成', CUR])
ws['A2'] = ('收入/支出按「钱的方向」认（折本位币为正=收，为负=支），'
            '内部转账（账户之间调头寸、购汇结汇）单独两列列出来，不算进收入和支出')
ws['A4'] = hdr(['一、按月汇总（', CUR, '）'])
for a, parts in (('B5', ['收入(', CUR, ')']), ('C5', ['支出(', CUR, ')']),
                 ('D5', ['净流入(', CUR, ')']), ('G5', ['月末资金总额(', CUR, '账面)']),
                 ('G21', ['本月收入(', CUR, ')']), ('H21', ['本月支出(', CUR, ')']),
                 ('I21', ['月末余额(', CUR, '账面)'])):
    ws[a] = hdr(parts)

wb['收支分类报表']['A1'] = hdr(['收支分类报表 · 按收支类别，全部折成', CUR])

ws = wb['资金日报表']
ws['A5'] = hdr(['一、按日走势（', CUR, '，不含内部转账）'])
for a, parts in (('B6', ['当日收款(', CUR, ')']), ('C6', ['当日付款(', CUR, ')']),
                 ('E6', ['当日资金总额(', CUR, '账面)']), ('I42', ['本日余额(', CUR, ')'])):
    ws[a] = hdr(parts)

ws = wb['区间查询']
ws['A1'] = hdr(['区间查询 · 任意起止日期，全部折成', CUR])
for a, parts in (('C8', ['金额(', CUR, ')']), ('B42', ['收入(', CUR, ')']),
                 ('C42', ['支出(', CUR, ')'])):
    ws[a] = hdr(parts)

# ══════════════════════════════════════════════════════════
# ⑥ 核对表：两个勾稽公式修正 ★真 bug
# ══════════════════════════════════════════════════════════
ws = wb['核对表']
ws['C5'] = hdr(['各账户「账面', CUR, '成本」合计 = 期初成本 + 全部流水折', CUR])
ws['C7'] = hdr(['分类报表「收入合计」= 流水里属性为收入的折', CUR, '合计'])
ws['C8'] = hdr(['分类报表「支出合计」= 流水里属性为支出的折', CUR, '合计'])
ws['C9'] = hdr(['按币种小计的「折', CUR, '」= 各账户「期末', CUR, '」合计'])
ws['F15'] = hdr(['这些币种的流水折不出', CUR, '，所有', CUR, '报表都会少这一块。'])
ws['C16'] = hdr(['内部转账折', CUR, '净额（购汇结汇的价差）'])

# 第 2 项：账户余额表把期初 ROUND 到两位再用，核对这边也得 ROUND，否则期初带小数就差几分
ws['D6'] = '=ROUND(SUM(账户余额表!$H$6:$H$35)-SUMPRODUCT(ROUND(账户期初,2))-SUM(流水净额),2)'
ws['F6'] = ('同上。（跨币种相加没有意义，但这个恒等式成立）'
            '★ 期初余额跟【账户余额表】一样四舍五入到分再比，所以期初带小数也不会差几分。')

# 第 6 项：原来写死 =6-COUNTA(账户名)，改成真去数「有几个账户确实有子表」。
# INDIRECT 不能吃数组参数（Excel 勉强、LibreOffice 直接不认），所以在 H 列一行一格地判，再求和。
ws['H4'] = '子表存在标记（别删，核对表第 6 项用）'
ws['H4']._style = copy(ws['C4']._style)
for i in range(30):
    src = f'参数设置!$C${11 + i}'
    ws[f'H{5 + i}'] = (f'=IF({src}="",0,IF(ISREF(INDIRECT("\'"&{src}&"\'!$A$1")),1,0))')
ws.column_dimensions['H'].hidden = True
CNT = 'SUM($H$5:$H$34)'
ws['D10'] = f'=COUNTA(账户名)-{CNT}'
ws['F10'] = (f'="现在 "&COUNTA(账户名)&" 个账户、"&{CNT}&" 张子表。'
             '不是 0 就是有账户还没建子表 —— 复制任意一张子表，改表名跟账户名一模一样，再把 B2 改成该账户名。"')
print('  ✓ 核对表：第 2 项改成同口径比、第 6 项改成真数子表（原来写死 6）')

# ══════════════════════════════════════════════════════════
# ⑦ 使用说明：措辞跟本位币走 + 补一节「跨币种换汇怎么录」
# ══════════════════════════════════════════════════════════
ws = wb['使用说明']
ws['A1'] = '外汇资金台账 · 使用说明（本位币：苏姆 UZS）'
ws['C5'] = ('每月填一次当月记账汇率。汇率的意思是「1 个原币 = 多少本位币」——'
            '本位币是苏姆，所以 CNY 填 1700 就是 1 元 = 1700 苏姆，USD 填 12000 就是 1 美元 = 12000 苏姆。'
            '只填你们在用的币种（人民币、美元）就行，苏姆那一列填不填都不影响。')
ws['C11'] = '每月一行。左边记账汇率（流水折本位币用），右边月末汇率（月末重估用，空着=用左边）。两边币种同一套、同一个顺序。'
ws['C14'] = '每账户一行：期末原币、期末本位币、账面成本、汇兑损益；下面还有按币种小计。'
ws['C15'] = '按月的本位币收入/支出/净流入/月末资金总额；下半张是报表月份的各账户明细。'
ws['C16'] = '收支类别 × 12 个月，折本位币。支出显示成正数，好读。'
ws['A26'] = '四、两套本位币口径，各算各的，千万别混着加'
ws['A27'] = '账面本位币成本'
ws['C27'] = '＝期初本位币成本 + 每一笔原币 × 该笔当时的汇率。钱进来时值多少就是多少，以后汇率怎么变都不动它。'
ws['A28'] = '期末本位币(重估)'
ws['A49'] = '· 【流水录入】里是你们 2026 年的真实流水，不是示例数据。'
ws['A50'] = '· 【月度汇率】已填 2026 年 1~12 月的 CNY / USD 记账汇率（1700 / 12000 那两列），月末汇率空着就自动用记账汇率。'
ws['A51'] = '· 某个币种汇率空着时，那个账户会显示「△××  还没填汇率」的提示。'
ws['A52'] = ('· 顺带说清楚：某个币种一个汇率都没填时，它的余额**进不了本位币合计数**（宁可不算，也不瞎算），'
             '那个账户的本位币几列会是空白而不是 0。')
ws['A53'] = '· 现有 5 个账户：人民币现金、美元现金、苏姆现金、NBU银行苏姆结算户-6688、公务卡苏姆结算户-9200。'

SH, SA, SB, SC = (copy(ws['A31']._style), copy(ws['A32']._style),
                  copy(ws['B32']._style), copy(ws['C32']._style))
BLOCK = [
    ('九、人民币换美元这种「跨币种换汇」怎么录', None, None),
    ('录两行', '一出一进', '在【流水录入】录两笔，类别都选「购汇/结汇」（属性=内部转账，不进收入支出）：'
               '① 人民币现金 —— 支出 278,800（原币 CNY）；② 美元现金 —— 收入 40,000（原币 USD）。'),
    ('汇率填什么', '永远填「折苏姆」的价', '★ 最容易搞错的一点：「实际成交汇率」那一列填的**不是** 6.97（人民币兑美元），'
                  '而是「1 个原币 = 多少苏姆」。所以人民币那一腿填 1700 左右，美元那一腿填 12000 左右。'
                  '留空的话自动取当月记账汇率。'),
    ('想让两腿正好轧平', '算一下美元腿的汇率', '美元腿汇率 = 人民币金额 × 人民币汇率 ÷ 美元金额。'
                  '例：278,800 × 1700 ÷ 40,000 = 11,849。这样两腿折苏姆都是 473,960,000，净额 0，不产生假的损益。'),
    ('想把换汇价差显示出来', '两腿都用记账汇率', '两腿都留空（各按当月记账汇率折）：人民币腿 473,960,000、'
                  '美元腿 40,000×12,000 = 480,000,000，差 6,040,000 苏姆。'
                  '这个差额会落在【核对表】第 12 项「内部转账折本位币净额」里 —— 那就是你这次换汇相对市场价的得失。'),
    ('两种都对，选一个用', '别混着来', '要「账实相符、不产生损益」就用第一种；要「看得见换汇赚亏」就用第二种。'
                  '同一家公司固定用一种，不然核对表第 12 项就读不出意思了。'),
    ('美元换苏姆 / 苏姆换人民币', '一样的套路', '本位币（苏姆）那一腿汇率恒等于 1，不用填；外币那一腿按上面的规则填。'),
]
r0 = 55
for i, (a, b, c) in enumerate(BLOCK):
    r = r0 + i
    ws[f'A{r}'] = a
    ws[f'A{r}']._style = SH if b is None else SA
    if b is not None:
        ws[f'B{r}'] = b; ws[f'B{r}']._style = SB
        ws[f'C{r}'] = c; ws[f'C{r}']._style = SC
    ws.row_dimensions[r].height = ws.row_dimensions[31 if b is None else 32].height
ws['C32'] = ('转出账户记一笔支出，转入账户记一笔收入，类别都选「内部转账」。'
             '购汇结汇选「购汇/结汇」，也是内部转账属性 —— 跨币种换汇的汇率怎么填，见下面第九节。')
print('  ✓ 使用说明：措辞跟本位币走，并补了第九节「人民币换美元怎么录」')

wb.calculation.fullCalcOnLoad = True
wb.save(OUT)
print(f'已写 {OUT}')
