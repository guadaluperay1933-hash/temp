# -*- coding: utf-8 -*-
from copy import copy
import openpyxl
SRC, DST = 'A052_final9.xlsx', 'A052_final10.xlsx'
LOG=[]
def log(t,m): LOG.append(f'[{t}] {m}'); print(f'[{t}] {m}')
wb = openpyxl.load_workbook(SRC)
F, I, L, P, R, S = (wb['资金流水'], wb['开票登记'], wb['应收应付台账'],
                    wb['项目核算表'], wb['月度汇报表'], wb['使用说明'])

# ── 修复 36：粘一行文本日期就能让整套报表全红 ────────────────────
for r in range(5, 3033):
    F[f'S{r}'] = f'=IF($B{r}="","",IF(ISNUMBER($B{r}),--TEXT($B{r},"yyyymm"),"日期非法"))'
for r in range(5, 505):
    I[f'R{r}'] = f'=IF($B{r}="","",IF(ISNUMBER($B{r}),--TEXT($B{r},"yyyymm"),"日期非法"))'
log('修复36', '【资金流水】S 列发生月、【开票登记】R 列开票归属月原来是 --TEXT(日期,"yyyymm")。'
              '使用说明第②步明确写"可从网银导出后粘贴"，而网银导出的日期常常是文本；'
              'TEXT 拿到文本会原样返回，再被 -- 强制转数就是报错。而 S 列是全表最核心的条件区'
              '（月度汇报表、趋势表、日报表几十个 SUMIFS 都拿它当 criteria_range），'
              'SUMIFS 的条件区里只要有一个错误值，整格直接报错 —— 粘错一行日期，整页汇报表全红，'
              '还看不出是哪一行造成的。本表就已经有一行（开票登记 B15 的 "2026-2-2-"）。'
              '现在遇到非日期返回"日期非法"四个字：报表照常算，那一行自己跳出来，一眼定位')

# ── 修复 37：勾稽校验加第 13 行：日期录成文本的行 ──────────────────
r = 186
for c in range(1,9): R.cell(r,c)._style = copy(R.cell(185,c)._style)
R.row_dimensions[r].height = R.row_dimensions[185].height
R[f'A{r}'] = '日期录成文本的行'
R[f'B{r}'] = '=COUNTIF(资金流水!$S$5:$S$3032,"日期非法")+COUNTIF(开票登记!$R$5:$R$504,"日期非法")'
R[f'C{r}'] = 0
R[f'D{r}'] = f'=N($B{r})-N($C{r})'
R[f'E{r}'] = f'=IF(ABS($D{r})<0.01,"√ 一致","✗ 有 "&TEXT($D{r},"0")&" 行日期不是真日期，这些行不进任何按月汇总")'
R[f'F{r}'] = '在「资金流水」S 列或「开票登记」R 列筛选"日期非法"即可定位，把该行日期重填一遍'
for c in (7,8): R.cell(r,c).value=None
R.merge_cells(f'F{r}:H{r}')
log('修复37', '【月度汇报表】勾稽校验加第 13 行：日期被录成文本的行会被数出来')

# ── 修复 38：三张长表打印时第 2 页起没有表头 ───────────────────────
for ws, rows in ((F,'4:4'), (I,'4:4'), (L,'4:4'), (P,'4:4')):
    ws.print_title_rows = rows
log('修复38', '【资金流水】【开票登记】【应收应付台账】【项目核算表】设置打印顶端标题行（第 4 行）。'
              '原来 3032 行的流水打出来，第 2 页往后全是裸数字列，对不上是哪一栏')

# ── 修复 39：12 行手工税额做个标记 ────────────────────────────────
n=0
for r in range(5, 505):
    v = I.cell(r,12).value
    if v is not None and not (isinstance(v,str) and v.startswith('=')):
        if not I.cell(r,20).value:
            I.cell(r,20).value = '税额按发票实际值手工填写（本行不随税率自动算）'
            n+=1
log('修复39', f'【开票登记】L 列有 {n} 行的税额是手工填的常量而不是公式 —— 这是**有意为之**，不是漏填：'
              f'这些发票的价税合计是整数（如 5,445.55+54.45=5,500.00、253,104.4+32,903.6=286,008.00），'
              f'税额是倒推出来的，与"不含税×税率"差几分钱。表头第 3 行登记规则⑤本来就写着'
              f'"与发票实际税额有出入可直接覆盖"。改回公式反而会让金额与真实发票对不上，'
              f'所以保留原值，只在备注列做了标记，以免以后被当成漏填的洞')

S['A82'] = ('⑬ 资金流水 S 列 / 开票登记 R 列改为能识别文本日期：网银导出的日期常常是文本，'
            '原写法遇到文本会报错，而这两列是全表最核心的筛选条件，一行出错整页汇报表全红。'
            '现在会显示"日期非法"，报表照常算，那一行自己跳出来。三张长表也补了打印顶端标题行。')
S['A82']._style = copy(S['A81']._style); S.row_dimensions[82].height = 31.5
S['A81'] = ('全表 43,344 条公式已用 LibreOffice 全量重算验证：0 处报错；换月份、换公司、换日期区间、换项目、'
            '切换含税/不含税口径分别跑过一遍，结构性的九项勾稽校验始终"√ 一致"，后四项如实反映录入缺口。'
            '另用 python 从录入表原始数据独立复算了 26 项关键数字（开票、现金、损益、期末资金、应收、项目毛利…），'
            '与表内计算结果 26/26 完全一致。')
wb.save(DST); open('fix16_log.txt','w',encoding='utf-8').write('\n'.join(LOG))
print('已保存', DST)
