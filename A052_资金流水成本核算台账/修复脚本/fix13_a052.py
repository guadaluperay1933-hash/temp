# -*- coding: utf-8 -*-
from copy import copy
import openpyxl
SRC, DST = 'A052_final4.xlsx', 'A052_final5.xlsx'
LOG=[]
def log(t,m): LOG.append(f'[{t}] {m}'); print(f'[{t}] {m}')
wb = openpyxl.load_workbook(SRC)
B, P, D, R, S = wb['基础资料'], wb['项目核算表'], wb['项目明细账'], wb['月度汇报表'], wb['使用说明']

# ── 修复 22：「已开票未收款」用倒算法，跨年回款会算成负数 ───────────
for r in range(5, 155):
    P[f'I{r}'] = f'=IF($B{r}="","",SUMIFS(开票登记!$P$5:$P$504,开票登记!$G$5:$G$504,$B{r}))'
D['I4'] = '=SUMIFS(开票登记!$P$5:$P$504,开票登记!$G$5:$G$504,$C$2)'
log('修复22', '【项目核算表】I 列「已开票未收款」原来是"本项目全部开票 − 本项目全部银行进账"倒算，'
              '隐含假设"所有到账都对应本表登记过的发票"。可使用说明第 37 条讲的正是相反的情形——'
              '收到去年项目的尾款，钱今年进、票去年开、去年那张票不在本表里，于是这一列直接变负数。'
              '实测倒算合计 −258.89 万，而「开票登记」P 列按票号核销的权威口径是 +529.70 万，差 788 万。'
              '现在直接取 开票登记 P 列（未收款），与收款状态、账龄严格同源。【项目明细账】I4 同步')

# ── 修复 23：成本合计与明细账两套算法 ─────────────────────────────
for r in range(5, 155):
    P[f'X{r}'] = (f'=IF($B{r}="","",SUMIFS(资金流水!$L$5:$L$3032,资金流水!$F$5:$F$3032,$B{r},'
                  f'资金流水!$W$5:$W$3032,"项目成本"))')
log('修复23', '【项目核算表】X 列「成本合计」原来是 SUM(J:W) 把 14 个成本类别列加起来，'
              '而【项目明细账】I3 认的是"支出大类=项目成本"。今天两者相等，但只要在基础资料里'
              '给某个成本类别改名（历史流水 H 列还是旧名字）、或加第 15 个成本类别，'
              'X 列就会整块漏掉、毛利虚高，两张表同一个项目给出两个成本。'
              '现在 X 列与明细账同源，J:W 十四列保留作为构成明细')

# ── 修复 24：项目明细账底部合计只统计显示出来的 200 行 ─────────────
D['G208'] = '=SUMIFS(资金流水!$K$5:$K$3032,资金流水!$F$5:$F$3032,$C$2)'
D['I208'] = '=SUMIFS(资金流水!$L$5:$L$3032,资金流水!$F$5:$F$3032,$C$2)'
D['N7'] = ('=IF(COUNTIFS(资金流水!$F$5:$F$3032,$C$2)>200,'
           '"⚠ 本项目共 "&COUNTIFS(资金流水!$F$5:$F$3032,$C$2)&" 笔，下面只列得下 200 笔，底部合计仍是全量","")')
D['N7']._style = copy(D['O7']._style)
log('修复24', '【项目明细账】底部"本项目合计"原来只加显示出来的 200 行，而顶部各项汇总是对整张流水'
              '算的全量数；项目笔数一旦超过 200，上下两个合计对不上还没有任何提示。'
              '现在底部合计改为与顶部同源的全量 SUMIFS，并在 N7 加了超 200 笔的提示')

# ── 修复 25：同名项目的合同金额在去重时丢了 ────────────────────────
MERGE = {
 '中电信数智科技有限公司昌吉分公司2025年某学校智慧教室建设项目': (1541150, '待整理：两份合同重名(295,570+1,245,580)，请拆成两个项目名'),
 '昌吉市南安幼儿园设备采购项目': (127155, '待整理：两份合同重名(100,000+27,155)，请拆成两个项目名'),
 '昌吉市第十九小学教学仪器设备采购项目': (12706500, None),
}
n=0
for r in range(4, 154):
    nm = B.cell(r,10).value
    if nm in MERGE:
        amt, note = MERGE[nm]
        B.cell(r,13).value = amt
        if note: B.cell(r,15).value = note
        n+=1
log('修复25', f'【基础资料】{n} 个项目的合同金额补正：项目档案里有 6 组重名，去重时只保留了第一行，'
              f'但其中 2 组其实是两份不同的合同用了同一个项目名（智慧教室 29.56 万 + 124.56 万、'
              f'南安幼儿园 10 万 + 2.72 万），合同额已合并、状态标了"待整理"，请拆成两个项目名；'
              f'第十九小学那组是同一份合同录了两个数（12,700,000 / 12,706,500），取后者')

# ── 修复 26：勾稽校验加一行，盯住重复的发票号 ──────────────────────
r = 184
for c in range(1,9): R.cell(r,c)._style = copy(R.cell(183,c)._style)
R.row_dimensions[r].height = R.row_dimensions[183].height
R[f'A{r}'] = '开票登记·重复的发票号'
R[f'B{r}'] = '=SUMPRODUCT((开票登记!$I$5:$I$504<>"")*(COUNTIF(开票登记!$I$5:$I$504,开票登记!$I$5:$I$504)>1))'
R[f'C{r}'] = 0
R[f'D{r}'] = f'=N($B{r})-N($C{r})'
R[f'E{r}'] = f'=IF(ABS($D{r})<0.01,"√ 一致","✗ 有 "&TEXT($D{r},"0")&" 行发票号重复，收款会被两行各核销一次")'
R[f'F{r}'] = '发票号是核销的钥匙，重号会让同一笔收款在两张票上各算一次已收款'
for c in (7,8): R.cell(r,c).value=None
R.merge_cells(f'F{r}:H{r}')
log('修复26', '【月度汇报表】勾稽校验加第 11 行：发票号重复检查。本表第 7、8 行的发票号都是 FP20260602，'
              '一旦有一笔收款在「资金流水」Q 列填了这个号，两张票会各核销一次，已收款凭空翻倍')

S['A79'] = ('⑩ 项目核算表的「已开票未收款」原来靠"累计开票 − 累计收款"倒算，跨年回款会算成负数，'
            '已改为直接取「开票登记」P 列；「成本合计」改为与项目明细账同源；项目明细账底部合计'
            '改为全量（原来只加显示出来的 200 行）。')
S['A79']._style = copy(S['A78']._style); S.row_dimensions[79].height = 31.5
wb.save(DST); open('fix13_log.txt','w',encoding='utf-8').write('\n'.join(LOG))
print('已保存', DST)
